"""Render captions as a self-contained SVG meme poster."""

from __future__ import annotations

import html
from pathlib import Path

from .captions import Caption

WIDTH = 1080
HEIGHT = 1080
MAX_CHARS = 22


def wrap_text(text: str, *, max_chars: int = MAX_CHARS) -> list[str]:
    """Wrap text on word boundaries, preserving explicit line breaks."""

    if max_chars < 1:
        raise ValueError("max_chars must be at least 1")

    lines: list[str] = []
    for paragraph in text.splitlines():
        words: list[str] = []
        for word in paragraph.split():
            while len(word) > max_chars:
                words.append(word[:max_chars])
                word = word[max_chars:]
            if word:
                words.append(word)

        current = ""
        for word in words:
            candidate = f"{current} {word}".strip()
            if len(candidate) <= max_chars:
                current = candidate
                continue
            if current:
                lines.append(current)
            current = word
        if current:
            lines.append(current)
    return lines


def _font_size(lines: list[str]) -> int:
    longest = max((len(line) for line in lines), default=0)
    if longest <= 10:
        return 84
    if longest <= 14:
        return 70
    if longest <= 18:
        return 58
    return 48


def _text_block(lines: list[str], *, x: int, y: int, size: int) -> str:
    if not lines:
        return ""
    line_height = round(size * 1.12)
    spans = [
        f'      <tspan x="{x}" dy="{0 if index == 0 else line_height}">{html.escape(line)}</tspan>'
        for index, line in enumerate(lines)
    ]
    return (
        f'    <text x="{x}" y="{y}" font-size="{size}" fill="#ffffff" stroke="#000000"\n'
        f'          stroke-width="10" stroke-linejoin="round" style="paint-order: stroke fill">\n'
        + "\n".join(spans)
        + "\n    </text>"
    )


def render_svg(
    caption: Caption,
    *,
    source: str = "",
    width: int = WIDTH,
    height: int = HEIGHT,
    max_chars: int = MAX_CHARS,
) -> str:
    """Return an SVG document for the caption."""

    top_lines = wrap_text(caption.top, max_chars=max_chars)
    bottom_lines = wrap_text(caption.bottom, max_chars=max_chars)
    all_lines = top_lines + bottom_lines
    size = _font_size(all_lines)
    line_height = round(size * 1.12)

    top_y = 100 + size
    bottom_y = height - 130 - max(0, len(bottom_lines) - 1) * line_height
    label = " — ".join(part for part in (caption.top, caption.bottom) if part)
    source_line = "newsmemeai" + (f" · {source}" if source else "")

    opening = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" aria-labelledby="title desc">\n'
    )
    footer = (
        f'  <text x="{width // 2}" y="{height - 44}" text-anchor="middle"\n'
        f"        font-family=\"'JetBrains Mono','SFMono-Regular',monospace\" "
        f'font-size="24" fill="#9aa4c7">{html.escape(source_line)}</text>\n'
        "</svg>\n"
    )

    return (
        f"{opening}"
        f'  <title id="title">{html.escape(label)}</title>\n'
        '  <desc id="desc">Meme draft generated by NewsMemeAI.</desc>\n'
        "  <defs>\n"
        '    <linearGradient id="background" x1="0" y1="0" x2="1" y2="1">\n'
        '      <stop offset="0" stop-color="#0b1020"/>\n'
        '      <stop offset="0.55" stop-color="#1b1040"/>\n'
        '      <stop offset="1" stop-color="#06131f"/>\n'
        "    </linearGradient>\n"
        '    <radialGradient id="glow" cx="0.5" cy="0.35" r="0.65">\n'
        '      <stop offset="0" stop-color="#5b3df5" stop-opacity="0.55"/>\n'
        '      <stop offset="1" stop-color="#5b3df5" stop-opacity="0"/>\n'
        "    </radialGradient>\n"
        "  </defs>\n"
        f'  <rect width="{width}" height="{height}" fill="url(#background)"/>\n'
        f'  <circle cx="{width // 2}" cy="{height // 3}" r="{width // 2}" '
        'fill="url(#glow)"/>\n'
        "  <g font-family=\"'Anton','Impact','Arial Black',sans-serif\" "
        'font-weight="900" text-anchor="middle">\n'
        f"{_text_block(top_lines, x=width // 2, y=top_y, size=size)}\n"
        f"{_text_block(bottom_lines, x=width // 2, y=bottom_y, size=size)}\n"
        "  </g>\n"
        f"{footer}"
    )


def write_svg(
    path: str | Path,
    caption: Caption,
    *,
    source: str = "",
    width: int = WIDTH,
    height: int = HEIGHT,
    max_chars: int = MAX_CHARS,
) -> Path:
    """Render a caption and write it to ``path``."""

    destination = Path(path).expanduser()
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(
        render_svg(
            caption,
            source=source,
            width=width,
            height=height,
            max_chars=max_chars,
        ),
        encoding="utf-8",
    )
    return destination
